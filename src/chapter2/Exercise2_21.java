// Exercise 2.21: What does the following code print?
package chapter2;

public class Exercise2_21
{
   public static void main( String[] args )
   {
      // print does NOT end the line, so everything lands on ONE line:
      // 1 + 3 + 5 + 4 + 2 = 15 asterisks
      System.out.print( "*" );
      System.out.print( "***" );
      System.out.print( "*****" );
      System.out.print( "****" );
      System.out.println( "**" );
   } // end main
} // end class Exercise2_21
