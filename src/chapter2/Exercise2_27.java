// Exercise 2.27: Checkerboard pattern of asterisks.
package chapter2;

public class Exercise2_27
{
   public static void main( String[] args )
   {
      // odd rows start at column 0, even rows are shifted right by one space
      System.out.println( "* * * * * * * *" );
      System.out.println( " * * * * * * * *" );
      System.out.println( "* * * * * * * *" );
      System.out.println( " * * * * * * * *" );
      System.out.println( "* * * * * * * *" );
      System.out.println( " * * * * * * * *" );
      System.out.println( "* * * * * * * *" );
      System.out.println( " * * * * * * * *" );
   } // end main
} // end class Exercise2_27
